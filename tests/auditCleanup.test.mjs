assert.equal(mayTrashAuditProcess(record,[{process_id:'proc-a',status:'running'}],owner),false);
assert.equal(mayTrashAuditProcess({...record,team_id:'shared-team'},[],owner),false);
assert.equal(mayTrashAuditProcess(record,[],'user-b'),false);

