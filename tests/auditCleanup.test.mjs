assert.equal(scopeCutoff(scopes,'292185'),Date.parse(now));
assert.equal(auditEventVisible({process_no:'292184',created_at:old},scopes),false);
assert.equal(auditEventVisible({process_no:'292185',created_at:old},scopes),false);
assert.equal(auditEventVisible({process_no:'292185',created_at:later},scopes),true);
assert.equal(auditEventVisible({process_no:'292184',created_at:later},scopes),true);
assert.equal(auditEventVisible({process_no:'292184',created_at:old},[]),true);
assert.equal(auditJobVisible({process_no:'292184',status:'completed',updated_at:old},scopes),false);
assert.equal(auditJobVisible({process_no:'292184',status:'failed',updated_at:later},scopes),true);
assert.equal(auditJobVisible({process_no:'292184',status:'queued',updated_at:old},scopes),true);
assert.equal(auditJobVisible({process_no:'292184',status:'running',updated_at:old},scopes),true);
assert.equal(auditJobVisible({process_no:'292184',status:'cancelled',updated_at:old},[]),true);
