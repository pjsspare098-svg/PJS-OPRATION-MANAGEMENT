const clock=Date.parse('2026-10-19T10:00:00Z');
const stale={job_type:'tracking',status:'running',started_at:new Date(clock-16*60_000).toISOString()};
const heartbeat=new Date(clock-6*60_000).toISOString();
assert.equal(isStaleTrackingJob(stale,heartbeat,clock),true);
assert.equal(isStaleTrackingJob(stale,new Date(clock-3*60_000).toISOString(),clock),false);
assert.equal(isStaleTrackingJob({...stale,started_at:new Date(clock-3*60_000).toISOString()},heartbeat,clock),false);
assert.equal(isStaleTrackingJob({...stale,job_type:'bill_submit'},heartbeat,clock),false);
assert.equal(isStaleTrackingJob({...stale,status:'completed'},heartbeat,clock),false);
assert.equal(isStaleTrackingJob(stale,null,clock),false);
