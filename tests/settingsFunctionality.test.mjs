import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';

const read=(path)=>readFileSync(new URL('../'+path,import.meta.url),'utf8');
const settings=read('src/SettingsControlCenter.tsx');
const reset=read('src/WorkspaceResetPanel.tsx');
const edge=read('supabase/functions/oms-personal-workspace-reset/index.ts');
const sql=read('supabase/migrations/023_personal_workspace_reset.sql');
const notifications=read('src/SettingsNotifications.tsx');
const office=read('src/WorkerFleetStatus.tsx');
const photos=read('src/DonePickListPage.tsx');
const app=read('src/UnifiedApp.tsx');
assert.ok(settings.includes('<WorkspaceResetPanel')&&settings.includes('<TeamWorkspace')); 
assert.ok(!settings.includes('<WorkerFleetStatus')&&!settings.includes('<SettingsNotifications'));
assert.ok(settings.includes('<PdfOcrTestBench/>'));
assert.ok(reset.includes('DELETE ALL MY PROCESSES'));
assert.ok(reset.includes('window.confirm('),'Require secondary explicit confirmation');
assert.ok(!reset.includes('preview.running_count===0'),'Historical Running markers must not permanently lock the reset button');
assert.ok(reset.includes('legacyRunning===0||workersStopped'),'Require owner acknowledgment that office workers were stopped');
assert.ok(reset.includes('workers_stopped:legacyRunning===0||workersStopped'),'Protected reset receives worker-stop acknowledgment');
assert.ok(edge.includes('body.workers_stopped!==true'),'Server refuses unacknowledged Running job cleanup');
assert.ok(reset.includes('managed backups'),'Must distinguish managed database backups from app files');
assert.ok(edge.includes('getUser(token)')&&edge.includes('ALLOWED_ORIGINS'),'Verify user/session on privileged edge');
assert.ok(edge.includes('x.path.split("/").some(segment=>segment==="."||segment===".."||segment==="")'),'Reject only actual unsafe path segments');
assert.ok(!edge.includes('x.path.includes("..")'),'Real uploaded PDF names with consecutive dots must not prevent a reset preview');
const unsafePath=(owner,path)=>!path.startsWith(owner+"/")||path.split("/").some(segment=>segment==="."||segment===".."||segment==="");
const uid='00000000-0000-4000-8000-000000000000';
assert.equal(unsafePath(uid,uid+'/process-id/scan..signed.pdf'),false,'Legitimate double-dot filename');
assert.equal(unsafePath(uid,uid+'/process-id/../../outside.pdf'),true,'Real parent segment must be rejected');
assert.equal(unsafePath(uid,'another-owner/process-id/invoice.pdf'),true,'Cross-owner storage path must be rejected');
assert.ok(reset.includes('readableResetError'),'Show server validation error instead of only non-2xx status');
assert.ok(reset.includes('Typing is locked until the server verifies'),'Explain why field is disabled on failed preview');

assert.ok(edge.includes('oms_prepare_personal_reset')&&edge.includes('oms_complete_personal_reset'),'Require atomic database-scoped preparation/finish');
assert.ok(edge.includes('.storage.from(bucket).remove(group)'),'Delete private storage files via Storage API');
assert.ok(sql.includes('where user_id=p_owner and team_id is null'),'Never delete shared team or another user data');
assert.ok(sql.includes('grant execute on function public.oms_prepare_personal_reset(uuid,integer) to service_role'));
assert.ok(sql.includes("state='preparing'"),'Retryable cleanup required');
assert.ok(!reset.includes('SUPABASE_SERVICE_ROLE_KEY')&&!settings.includes('SUPABASE_SERVICE_ROLE_KEY'),'No server secrets in browser');
assert.ok(notifications.includes('oms_agent_notifications')&&notifications.includes("read_at:new Date().toISOString()"));
assert.ok(office.includes('oms_office_workers')&&!office.includes('oms_outlook_workers'),'DataDoc worker only');
assert.ok(!office.includes('oms_tracking_workers'),'Retired carrier automation worker must not be polled or listed');
assert.ok(photos.includes('pjs_oms_photo_batch_limit_v1'));
assert.ok(app.includes('pjs_oms_landing_page_v1'));
console.log('PASS: Reset safeguards and manual-only Settings retain security, users, OCR and backups');
