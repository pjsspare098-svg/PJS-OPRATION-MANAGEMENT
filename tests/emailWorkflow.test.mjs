import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {OUTLOOK_DRAFT_VERSION,emailDraftReadiness,dispatchDetailsText} from '../src/emailWorkflow.ts';
const record={id:'one',owner_id:'u',current_user_id:'u',process:'292168',party:'Test Customer',so:'26271016',invoice:'946',productName:'PJ Spares',sales:'Vivek Pal',po:'PO-100',poDate:'2026-10-07',invoiceDate:'2026-10-08',transporter:'TCI',lr:'LR-100',courierDate:'2026-10-09',weight:'12',documents:[{id:'eml-1',kind:'emailDoc',name:'Original.eml'},{id:'inv-1',kind:'invoiceDoc',name:'Invoice.pdf'},{id:'lr-1',kind:'lrDoc',name:'receipt.pdf'}]};
assert.equal(OUTLOOK_DRAFT_VERSION,'outlook_draft_v1');
assert.equal(emailDraftReadiness(record).ready,true);
assert.equal(emailDraftReadiness({...record,owner_id:'other'}).ready,false);
assert.equal(emailDraftReadiness({...record,documents:[]}).ready,false);
assert.equal(emailDraftReadiness({...record,documents:record.documents.filter(x=>x.kind!=='invoiceDoc')}).ready,false);
assert.equal(emailDraftReadiness({...record,documents:[...record.documents,{id:'eml-2',kind:'emailDoc',name:'Other.eml'}]}).ready,false);
assert.equal(emailDraftReadiness({...record,selected_email_document_id:'eml-2',documents:[...record.documents,{id:'eml-2',kind:'emailDoc',name:'Other.eml'}]}).ready,true);
const job={job_type:'email_reply',process_id:'one',status:'queued',payload:{},id:'legacy'};
assert.equal(emailDraftReadiness(record,[job]).legacy,true);
assert.equal(emailDraftReadiness(record,[{...job,payload:{automation_version:OUTLOOK_DRAFT_VERSION}}]).legacy,false);
const body=dispatchDetailsText(record);
assert.ok(body.includes('PO-100')&&body.includes('09/10/2026')&&body.includes('Invoice No.: 946'));
assert.ok(body.startsWith('Dear Sir,')&&body.includes('CHETAN SOLANKI'));
assert.ok(body.includes('Please record a proper video')&&body.includes('Dispatch@pressurejet.com'));
assert.ok(body.includes('Box Weight (Kgs): 12'));
assert.ok(!body.includes('To:')&&!body.includes('Cc:'),'No recipient extraction or reconstruction');
const page=readFileSync(new URL('../src/EmailToClientWorkflow.tsx',import.meta.url),'utf8');
assert.ok(page.includes('Outlook sending and carrier tracking are manual'));
assert.ok(page.includes('I sent this in Outlook · Track'));
assert.ok(page.includes('Download original email'));
assert.ok(!page.includes('Saved dispatch recipients'));
assert.ok(page.includes('ux-pressurejet-email-table'),'Structured customer email table must render');
assert.equal(emailDraftReadiness({...record,weight:''}).ready,false);
assert.equal(emailDraftReadiness({...record,documents:record.documents.filter(d=>d.kind!=='lrDoc')}).ready,false);
const operations=readFileSync(new URL('../src/unifiedOps.ts',import.meta.url),'utf8');
assert.ok(operations.includes("if(type!=='bill_submit')throw Error("));
const app=readFileSync(new URL('../src/UnifiedApp.tsx',import.meta.url),'utf8');
assert.ok(app.includes('automatic_sent_verification:false'));
assert.ok(!app.includes('confirmedDraft'),'Manual confirmation must not depend on a worker draft');
console.log('PASS: Manual Outlook Reply All, file download, preview and operator-confirmed send');
