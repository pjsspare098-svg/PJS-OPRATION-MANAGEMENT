const sheet=read('src/DispatchTrackingPage.tsx');
const dialog=read('src/CarrierBulkTrashDialog.tsx');
const ops=read('src/unifiedOps.ts');
const sql=read('supabase/migrations/031_dispatch_carrier_bulk_trash.sql');

assert.match(sheet,/className='ux-track-bulk-delete'/);
assert.match(sheet,/carrierFilter==='All carriers'/);
assert.match(sheet,/setBulkCarrier\(carrierFilter\)/);
assert.match(sheet,/<CarrierBulkTrashDialog/);
assert.match(sheet,/onCompleted=\{async result=>/);
assert.match(sheet,/p.onRefresh\?\.\(\)/,'Refresh processes after bulk trash');
assert.match(sheet,/ShreeMarutiImport/,'Preserve Shree Maruti Excel intake');
assert.match(sheet,/<TransportTrackingCapture/,'Preserve manual screenshot handling');
assert.match(sheet,/function transfer/,'Preserve process transfer');
assert.doesNotMatch(sheet,/onBatchTrackShreeMaruti|onQueue\(/,'Bulk-delete must not trigger automation');
assert.match(dialog,/previewDispatchCarrierTrash\(carrier\)/,'Get preview server side, not from limited local UI records');
assert.match(dialog,/moveDispatchCarrierToTrash\(preview,confirmation\)/);
assert.match(dialog,/confirmation!==phrase/,'Require exact typed confirmation');
assert.match(dialog,/preview\.eligible<=0/,'Never enable a zero-process deletion');
assert.match(dialog,/!window.confirm\(/,'Secondary operator confirmation');
assert.match(dialog,/not just rows matching your search or status filter/);
assert.match(dialog,/Data Store → Deleted Processes/,'Communicate recovery route');
assert.match(dialog,/preview\.blocked_processes/,'List blocked process numbers');
