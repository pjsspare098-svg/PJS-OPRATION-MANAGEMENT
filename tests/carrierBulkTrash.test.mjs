import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {manualCarrierName} from '../src/manualDispatchTracking.ts';
const read=(path)=>readFileSync(new URL('../'+path,import.meta.url),'utf8');
const carriers=['SHREE MARUTI','VRL','TCI FREIGHT','TCI EXPRESS','V EXPRESS','V TRANS','ACPL','ARC','DTDC'];
for(const carrier of carriers)assert.equal(manualCarrierName(carrier),carrier,'Dropdown selection must use the exact canonical carrier');
