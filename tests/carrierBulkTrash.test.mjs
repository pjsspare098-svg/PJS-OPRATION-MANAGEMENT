assert.match(sql,/insert into public\.oms_events/,'Log each moved Process No.');
assert.match(sql,/grant execute on function public\.oms_preview_dispatch_carrier_trash\(text\)\s+to authenticated/);
assert.match(sql,/grant execute on function public\.oms_move_dispatch_carrier_to_trash\(text,text,text\)\s+to authenticated/);
assert.doesNotMatch(sql,/\bdelete\s+from\s+public\.oms_(processes|documents|events|jobs)/i,'No permanent deletion of processes/docs/jobs/events');
assert.doesNotMatch(sql,/\b(update|delete)\s+public\.oms_jobs\b/i,'Never change active jobs');
